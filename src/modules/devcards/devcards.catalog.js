// Возвращает каталог одной группы в удобном для фронта виде:
// { key, label, areas: [{ key, label, skills: [{ no, text }] }] }
function catalogFor(ageGroup) {
  const g = GROUPS[ageGroup];
  if (!g) return null;
  const byArea = new Map();
  for (const s of g.skills) {
    if (!byArea.has(s.area)) byArea.set(s.area, []);
    byArea.get(s.area).push({ no: s.no, text: s.text });
  }
  const areas = [...byArea.entries()].map(([key, skills]) => ({
    key,
    label: AREAS[key],
    skills,
  }));
  return { key: ageGroup, label: g.label, areas };
}

// Множество допустимых номеров навыков для группы (для валидации оценок).
function skillNumbers(ageGroup) {
  const g = GROUPS[ageGroup];
  return g ? new Set(g.skills.map((s) => s.no)) : new Set();
}

